package ruotadellafortuna.coredelgioco;
    /**
     * Contiene tutte le possibili fasi del gioco
     */

    public enum Stato{    
        /** La fase di avvio */ INIZIALIZZAZIONE,    
       /** Inizio del round */ INIZIO_ROUND,    
        /** La fine del round */ FINE_ROUND,    
       /** La fase finale */ FASE_FINALE,    
       /** Chiusura del programma, il gioco è finito */ FINE_GIOCO
    }
    

